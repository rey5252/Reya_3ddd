    private static final int ACT_TOTAL;
    private static final int[] ACT_START;

    static {
        ACT_START = new int[ACT_MS.length];
        int t = 0;
        for (int i = 0; i < ACT_MS.length; i++) {
            ACT_START[i] = t;
            t += ACT_MS[i];
        }
        ACT_TOTAL = t;
    }

    void draw(GuiGraphics g, int left, int top) {
        long now = Util.getMillis();
        drifting(g, left, top, now);
        for (int i = 0; i < TENTACLES.length; i++) {
            float[] tc = TENTACLES[i];
            int ox = Math.round(tc[0] - (SIZE / 2.0F - REACH * tc[2]));
            int oy = Math.round(tc[1] - (SIZE / 2.0F - REACH * tc[3]));
            if (CATCHER[i]) {
                act(g, left, top, i, ox, oy, now);
            } else {
                int frame = (int) ((now / FRAME_MS + i * 7L) % FRAMES);
                g.blit(SHEET, left + ox, top + oy, frame * SIZE, ROW[i] * SIZE, SIZE, SIZE, SIZE * FRAMES, SIZE * OTHERS);
            }
        }
    }

    /** Stars drifting in round the tentacles, faster as they get near, fading in far out. */
    private static void drifting(GuiGraphics g, int left, int top, long now) {
        double t = now / 1000.0D;
        for (int k = 0; k < 26; k++) {
            float[] tc = TENTACLES[k % TENTACLES.length];
            double speed = 0.12D + (k * 37 % 10) * 0.012D;
            double p = (t * speed + k * 0.37D) % 1.0D;
            double side = ((k * 7) % 5 - 2) * 5.0D + (k % 3 - 1) * 2.0D;
            double far = tc[4] * (0.8D + (k % 4) * 0.12D);
            double sx = tc[0] + tc[2] * far - tc[3] * side, sy = tc[1] + tc[3] * far + tc[2] * side;
            double ex = tc[0] - tc[2] * 4.0D, ey = tc[1] - tc[3] * 4.0D;
            double e = Math.pow(p, 1.6D);
            int kind = k % 3 == 0 ? 2 : k % 3 == 1 ? 0 : 1;
            star(g, left + (int) Math.round(sx + (ex - sx) * e), top + (int) Math.round(sy + (ey - sy) * e),
                    kind, (k / 3) % 3, (int) ((now / (120L + k % 4 * 30L) + k) % 8), (float) Math.min(1.0D, p / 0.25D));
        }
    }

    /** A catcher's act: its frame, and its star doing what the act says. */
    private static void act(GuiGraphics g, int left, int top, int i, int ox, int oy, long now) {
        int c = ROW[i];
        long shifted = now + c * 1811L;
        long round = shifted / ACT_TOTAL;                      // which time round: the burst changes each time
        int t = (int) (shifted % ACT_TOTAL);
        int f = 0;
        while (f + 1 < ACT_MS.length && ACT_START[f + 1] <= t) f++;
        float frac = (t - ACT_START[f]) / (float) ACT_MS[f];
        g.blit(ACTS, left + ox, top + oy, f * SIZE, c * SIZE, SIZE, SIZE, SIZE * ACT_MS.length, SIZE * CATCHERS);
        int state = ACT_STATE[f];
        if (state == 0) return;
        int[] here = ACT_STAR[c][f];
        int next = (f + 1) % ACT_MS.length;
        float x = here[0], y = here[1];
        if (ACT_STATE[next] != 0 && next != 0) {               // glide to the next frame's place
            x += (ACT_STAR[c][next][0] - here[0]) * frac;
            y += (ACT_STAR[c][next][1] - here[1]) * frac;
        }
        int colour = (int) ((round + c) % 3);
        int sx = left + ox + Math.round(x), sy = top + oy + Math.round(y);
        switch (state) {
            case 1 -> star(g, sx, sy, 2, colour, (int) ((now / 140L) % 8), f < 2 ? (f + frac) / 2.0F : 1.0F);
            case 2 -> star(g, sx, sy, 2, colour, 3 + (int) ((now / 200L) % 2), 1.0F);
            case 3 -> {                                        // struggling: shaking, flickering, throwing sparks
                int jx = (int) (hash(now / 70L + c) % 3) - 1, jy = (int) (hash(now / 70L + c + 99) % 3) - 1;
                star(g, sx + jx, sy + jy, 2, colour, 2 + (int) ((now / 60L) % 4), 1.0F);
                for (int k = 0; k < 3; k++) {
                    long h = hash(now / 90L * 7 + k + c * 13);
                    float life = (now % 90L) / 90.0F;
                    int px = sx + (int) (h % 9) - 4, py = sy + (int) ((h >> 8) % 9) - 4;
                    g.fill(px, py, px + 1, py + 1, alpha(1.0F - life) | STAR_RGB[colour]);
                }
            }
            default -> {                                       // breaking free and fleeing
                int escape = ACT_START[firstOf(4)];
                float since = (t - escape) / 1000.0F;
                float fade = state == 5 ? 1.0F - (t - ACT_START[firstOf(5)]) / (float) (ACT_TOTAL - ACT_START[firstOf(5)]) : 1.0F;
                burst(g, left + ox + ACT_STAR[c][firstOf(4)][0], top + oy + ACT_STAR[c][firstOf(4)][1], since, (int) ((round + c) % 3), colour);
                star(g, sx, sy, 2, colour, state == 4 ? 4 : (int) ((now / 100L) % 8), fade);
            }
        }
    }

    /** The burst when a star breaks free: a ring of light, a shower of little stars, or a flash of rays. */
    private static void burst(GuiGraphics g, int cx, int cy, float since, int kind, int colour) {
        if (since < 0.0F || since > 0.6F) return;
        float p = since / 0.6F;
        int rgb = STAR_RGB[colour];
        if (since < 0.08F) g.fill(cx - 2, cy - 2, cx + 3, cy + 3, alpha(0.8F) | 0xFFFFFF);   // the flash
        switch (kind) {
            case 0 -> {                                        // a ring spreading out
                float r = 2.0F + p * 12.0F;
                for (int a = 0; a < 28; a++) {
                    double ang = a * Math.PI * 2 / 28;
                    int px = cx + Math.round((float) Math.cos(ang) * r), py = cy + Math.round((float) Math.sin(ang) * r);
                    g.fill(px, py, px + 1, py + 1, alpha(1.0F - p) | rgb);
                }
            }
            case 1 -> {                                        // little stars flying off
                for (int a = 0; a < 9; a++) {
                    double ang = a * Math.PI * 2 / 9 + 0.3;
                    float r = 2.0F + p * (10.0F + a % 3 * 3.0F);
                    star(g, cx + Math.round((float) Math.cos(ang) * r), cy + Math.round((float) Math.sin(ang) * r) + Math.round(p * p * 4.0F),
                            0, (colour + a) % 3, 1 + a % 3, 1.0F - p);
                }
            }
            default -> {                                       // rays shooting out
                for (int a = 0; a < 8; a++) {
                    double ang = a * Math.PI / 4;
                    float r0 = 2.0F + p * 8.0F, r1 = r0 + (a % 2 == 0 ? 6.0F : 3.0F) * (1.0F - p);
                    for (float r = r0; r <= r1; r += 1.0F) {
                        int px = cx + Math.round((float) Math.cos(ang) * r), py = cy + Math.round((float) Math.sin(ang) * r);
                        g.fill(px, py, px + 1, py + 1, alpha(1.0F - p) | rgb);
                    }
                }
            }
        }
    }

    private static int firstOf(int state) {
        for (int i = 0; i < ACT_STATE.length; i++) if (ACT_STATE[i] == state) return i;
        return 0;
    }

    private static int alpha(float a) {
        return (int) (Mth.clamp(a, 0.0F, 1.0F) * 255.0F) << 24;
    }

    private static long hash(long v) {
        v ^= v >>> 33;
        v *= 0xFF51AFD7ED558CCDL;
        v ^= v >>> 33;
        return v & Long.MAX_VALUE;
    }

    /** One star from the sheet: kind (sparkle, four-, eight-pointed), colour (pink, gold, ice), frame. */
    private static void star(GuiGraphics g, int x, int y, int kind, int colour, int frame, float alpha) {
        if (alpha <= 0.02F) return;
        RenderSystem.enableBlend();
        RenderSystem.setShaderColor(1.0F, 1.0F, 1.0F, Math.min(1.0F, alpha));
        g.blit(STARS, x - 5, y - 5, frame * 11, (kind * 3 + colour) * 11, 11, 11, 88, 99);
        RenderSystem.setShaderColor(1.0F, 1.0F, 1.0F, 1.0F);
    }
