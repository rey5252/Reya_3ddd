/**
 * The tentacles round the vacuum chest's GUI and the stars they hunt. They are drawn frame by frame
 * by tools/gen_tentacles.py (glossy back with dark spots, pink underside with round suckers, the tip
 * curled; three colourings, each tentacle its own); their roots are under the frame, which is drawn
 * over them.
 * <p>
 * Most of them sway slowly, are drawn in and reach out again, and now and then snap at the air
 * (32 frames a loop, vacuum_chest_tentacles.png). The catchers play an act (vacuum_chest_catchers.png):
 * a star drifts in to the tip, the tentacle lunges and curls round it, drags it into the chest and
 * stays in there a while, comes out again holding it; the star struggles, the tentacle thrashes,
 * the star breaks free in a burst (a ring of light, a shower of little stars, or a flash of rays,
 * by turns) as the tip whips open, and the tentacle snatches after it and misses.
 * More stars drift in round them all: little sparkles, four- and eight-pointed stars, pink, gold, ice blue.
 */
